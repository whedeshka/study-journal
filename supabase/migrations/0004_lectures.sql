-- Отдельная библиотека лекций (файлы и/или внешние ссылки)
create table if not exists public.lectures (
 id bigint generated by default as identity primary key,
 subject text not null,
 title text not null,
 description text not null default '',
 file_name text,
 mime_type text,
 storage_path text unique,
 external_url text,
 created_at timestamptz not null default now(),
 constraint lectures_file_or_link check (
   nullif(storage_path, '') is not null or nullif(external_url, '') is not null
 )
);

alter table public.lectures enable row level security;

drop policy if exists "public read lectures" on public.lectures;
create policy "public read lectures" on public.lectures
 for select to anon, authenticated using (true);

drop policy if exists "admin manage lectures" on public.lectures;
create policy "admin manage lectures" on public.lectures
 for all to authenticated
 using (public.is_journal_admin())
 with check (public.is_journal_admin());

grant select on public.lectures to anon, authenticated;
grant insert, update, delete on public.lectures to authenticated;
grant usage, select on sequence public.lectures_id_seq to authenticated;
