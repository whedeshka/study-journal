-- Учебный журнал: Supabase Database + Storage
create table if not exists public.lessons (
 id bigint generated by default as identity primary key,
 subject text not null, week int not null check (week in (1,2)),
 weekday int not null check (weekday between 1 and 6),
 time text not null, room text not null default ''
);
create table if not exists public.admin_users (
 user_id uuid primary key references auth.users(id) on delete cascade
);
create or replace function public.is_journal_admin() returns boolean
language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.admin_users where user_id = auth.uid()) $$;
create table if not exists public.tasks (
 id bigint generated by default as identity primary key,
 lesson_id bigint not null references public.lessons(id) on delete cascade,
 lesson_date date not null,
 title text not null, description text not null default '',
 due_date date, created_at timestamptz not null default now(),
 expires_at timestamptz not null
);
create table if not exists public.attachments (
 id bigint generated by default as identity primary key,
 task_id bigint not null references public.tasks(id) on delete cascade,
 file_name text not null, mime_type text not null,
 storage_path text not null unique,
 created_at timestamptz not null default now()
);
alter table public.lessons enable row level security;
alter table public.tasks enable row level security;
alter table public.attachments enable row level security;
alter table public.admin_users enable row level security;
create policy "public read lessons" on public.lessons for select to anon, authenticated using (true);
create policy "admin manage lessons" on public.lessons for all to authenticated using (public.is_journal_admin()) with check (public.is_journal_admin());
create policy "public read tasks" on public.tasks for select to anon, authenticated using (true);
create policy "admin manage tasks" on public.tasks for all to authenticated using (public.is_journal_admin()) with check (public.is_journal_admin());
create policy "public read attachment metadata" on public.attachments for select to anon, authenticated using (true);
create policy "admin manage attachment metadata" on public.attachments for all to authenticated using (public.is_journal_admin()) with check (public.is_journal_admin());
create policy "admin list admins" on public.admin_users for select to authenticated using (user_id=auth.uid());
-- Private bucket: anonymous users may read/download objects, but only listed admins may upload/delete.
create policy "public read homework objects" on storage.objects for select to anon, authenticated using (bucket_id='homework-files');
create policy "admin upload homework objects" on storage.objects for insert to authenticated with check (bucket_id='homework-files' and public.is_journal_admin());
create policy "admin delete homework objects" on storage.objects for delete to authenticated using (bucket_id='homework-files' and public.is_journal_admin());
