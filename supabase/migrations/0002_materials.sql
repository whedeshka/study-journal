-- Библиотека учебных материалов
create table if not exists public.materials (
 id bigint generated by default as identity primary key,
 subject text not null,
 title text not null,
 description text not null default '',
 file_name text not null,
 mime_type text not null,
 storage_path text not null unique,
 created_at timestamptz not null default now()
);
alter table public.materials enable row level security;
create policy "public read materials" on public.materials
 for select to anon, authenticated using (true);
create policy "admin manage materials" on public.materials
 for all to authenticated using (public.is_journal_admin())
 with check (public.is_journal_admin());
